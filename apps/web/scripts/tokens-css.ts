// Writes src/styles/tokens.generated.css from the shared design tokens. Run by predev and prebuild.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { colors, fonts, shadows, radii, type, type TextStyleToken } from "../../../packages/ui-tokens/src/tokens.ts";

const outFile = fileURLToPath(new URL("../src/styles/tokens.generated.css", import.meta.url));

// camelCase token key to kebab-case CSS name, e.g. poloInk to polo-ink.
function kebab(key: string): string {
  return key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

// Color and shadow custom properties for one scheme, one per line.
function schemeVars(scheme: "light" | "dark"): string[] {
  const lines = Object.entries(colors[scheme]).map(([key, value]) => `--color-${kebab(key)}: ${value};`);
  for (const [key, value] of Object.entries(shadows[scheme])) lines.push(`--shadow-${kebab(key)}: ${value};`);
  return lines;
}

const indent = (lines: string[], spaces: string) => lines.map((line) => `${spaces}${line}`).join("\n");

const radiusLines = Object.entries(radii).map(([key, value]) => `--radius-${kebab(key)}: ${value}px;`);

// One @utility per type role, e.g. type-hero, carrying font, size, weight, line height and tracking.
function typeUtility(role: string, token: TextStyleToken): string {
  const lines = [
    `font-family: var(--font-${token.font});`,
    `font-size: ${token.size}px;`,
    `font-weight: ${token.weight};`,
    `line-height: ${token.lineHeight ?? 1.4};`,
  ];
  if (token.letterSpacing !== undefined) lines.push(`letter-spacing: ${token.letterSpacing}em;`);
  if (token.uppercase) lines.push("text-transform: uppercase;");
  return `@utility type-${kebab(role)} {\n${indent(lines, "  ")}\n}`;
}

const typeUtilities = Object.entries(type)
  .map(([role, token]: [string, TextStyleToken]) => typeUtility(role, token))
  .join("\n\n");

const css = `/* Generated by scripts/tokens-css.ts from packages/ui-tokens. Do not edit. */

@theme {
${indent(schemeVars("light"), "  ")}
${indent(radiusLines, "  ")}
  --font-display: "${fonts.display}", ui-sans-serif, system-ui, sans-serif;
  --font-body: "${fonts.body}", ui-sans-serif, system-ui, sans-serif;
}

${typeUtilities}

@media (prefers-color-scheme: dark) {
  :root {
${indent(schemeVars("dark"), "    ")}
  }
}
`;

writeFileSync(outFile, css);
console.log(`wrote ${outFile}`);
